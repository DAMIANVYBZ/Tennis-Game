"""Generate matching client/server versions and stage the static Cloudflare release."""
from pathlib import Path
import hashlib,json,shutil,sys
ROOT=Path(__file__).resolve().parents[1]
runtime=[p for p in ROOT.iterdir() if p.is_file() and p.suffix in ['.js','.mjs','.css','.html'] and p.name!='build-version.mjs']
runtime += [ROOT/'_headers']
for directory in ['assets','vendor']:
 runtime += [p for p in (ROOT/directory).rglob('*') if p.is_file()]
hash=hashlib.sha256()
for path in sorted(runtime):
 hash.update(path.relative_to(ROOT).as_posix().encode()+b'\0');hash.update(path.read_bytes())
version=hash.hexdigest()[:20]
(ROOT/'build-version.mjs').write_text(f"// Generated by tools/prepare-release.py.\nexport const BUILD_VERSION='{version}';\n")
(ROOT/'version.json').write_text(json.dumps({'version':version})+'\n')
if len(sys.argv)>1:
 target=Path(sys.argv[1]).resolve()
 if target==ROOT or ROOT in target.parents:raise SystemExit('Use a separate release directory outside this repository.')
 target.mkdir(parents=True,exist_ok=True)
 for path in runtime+[ROOT/'build-version.mjs',ROOT/'version.json']:
  out=target/path.relative_to(ROOT);out.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(path,out)
print('Prepared version '+version)
